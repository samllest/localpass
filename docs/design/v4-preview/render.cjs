const path = require('node:path')
const { pathToFileURL } = require('node:url')
const { chromium } = require(path.join(require('node:os').tmpdir(), 'localpass-ui-qa/node_modules/playwright'))

;(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
  const page = await browser.newPage({ viewport: { width: 1440, height: 940 }, deviceScaleFactor: 1.5 })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(pathToFileURL(path.join(__dirname, 'preview.html')).href)
  await page.evaluate(() => document.fonts.ready)
  await page.screenshot({ path: path.join(__dirname, 'overview.png') })
  await page.getByRole('button', { name: '编辑', exact: true }).click()
  await page.locator('#edit-port').focus()
  await page.screenshot({ path: path.join(__dirname, 'edit-dialog.png') })
  await page.keyboard.press('Escape')
  await page.locator('[data-index="1"]').click()
  if (!(await page.locator('#hero-host').innerText()).endsWith(':8080')) throw new Error('Port selection failed')
  await page.locator('#search').fill('5000')
  if (await page.locator('.site-row').count() !== 1) throw new Error('Port search failed')
  await page.locator('#search').fill('')
  await page.locator('[data-index="0"]').click()
  const overflow = await page.evaluate(() => ({ document: document.documentElement.scrollWidth > innerWidth, details: document.querySelector('.details').scrollWidth > document.querySelector('.details').clientWidth }))
  await page.setViewportSize({ width: 1100, height: 900 })
  await page.screenshot({ path: path.join(__dirname, 'compact.png') })
  const compactOverflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)
  await browser.close()
  if (errors.length || overflow.document || overflow.details || compactOverflow) throw new Error(JSON.stringify({ errors, overflow, compactOverflow }))
  console.log('Preview rendered: main view + edit dialog. Sample selection/search passed. No runtime errors or horizontal overflow at 1440px / 1100px.')
})().catch(error => { console.error(error); process.exitCode = 1 })
